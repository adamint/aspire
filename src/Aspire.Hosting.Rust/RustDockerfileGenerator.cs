using System.Collections.ObjectModel;
using Aspire.Hosting.ApplicationModel;
using Aspire.Hosting.ApplicationModel.Docker;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;

namespace Aspire.Hosting.Rust;

/// <summary>
/// Generates the multi-stage Dockerfile that publishes a <see cref="RustAppResource"/>.
/// </summary>
/// <remarks>
/// The container build is the only build: nothing here compiles the crate on the host. The single piece of
/// host-side information the Dockerfile needs is the name of the binary cargo will produce, which comes from
/// <c>cargo metadata</c> — a manifest query that neither compiles nor downloads dependencies.
/// </remarks>
internal static class RustDockerfileGenerator
{
    // Cargo's output directory inside the build stage. The build context is copied wholesale, so a crate's
    // .cargo/config.toml comes with it and its build.target-dir would otherwise move the binary somewhere the
    // COPY --from below does not look. Pinning it to a path outside /app also keeps build output away from the
    // copied sources.
    private const string ContainerTargetDirectory = "/build/target";

    // Where the build stage leaves the binary for the runtime stage to copy. Cargo's own output path
    // contains a triple directory whenever a target is selected, and .cargo/config.toml (which arrives with
    // the build context) can select one without the app host ever seeing it, so the binary is collected to
    // this fixed path instead of the runtime stage predicting cargo's layout.
    private const string ContainerArtifactDirectory = "/build/bin";

    // Default .dockerignore emitted next to the generated Dockerfile using BuildKit's per-Dockerfile ignore
    // convention. The build stage does `COPY . .`, so without this a local `target/` directory is uploaded to
    // the daemon as build context and copied into the build stage: it is routinely several gigabytes after a
    // debug run, and none of it is usable because the container rebuilds from source anyway. Cargo places a
    // target directory next to every manifest it is invoked against, hence the recursive pattern as well.
    // See https://docs.docker.com/build/concepts/context/#filename-and-location.
    private const string DefaultRustBuildContextIgnoreContent = """
        # Generated by Aspire. Author <contextRoot>/.dockerignore to take over these rules.
        target
        **/target
        .git
        .gitignore
        .DS_Store
        .env
        .env.*
        .aspire
        aspire-output
        Dockerfile
        Dockerfile.*
        *.Dockerfile
        *.Dockerfile.dockerignore
        .dockerignore

        """;

    public static async Task WriteAsync(RustAppResource resource, string appDirectory, DockerfileBuilderCallbackContext context)
    {
        var logger = context.Services.GetService<ILogger<RustAppResource>>();

        // Guarded because WithDockerfileBuilder always adds the annotation, but this stays robust if that
        // changes. Only set when nothing else has, so an explicit choice by the user or a future caller wins.
        //
        // A <dockerfile>.dockerignore takes precedence over the context root's .dockerignore rather than
        // merging with it, so emitting one unconditionally would silently discard rules the crate author
        // wrote. An authored .dockerignore therefore wins outright and the defaults are skipped.
        if (context.Resource.TryGetLastAnnotation<DockerfileBuildAnnotation>(out var dockerfileBuildAnnotation)
            && !File.Exists(Path.Combine(appDirectory, ".dockerignore")))
        {
            dockerfileBuildAnnotation.BuildContextIgnoreContent ??= DefaultRustBuildContextIgnoreContent;
        }

        // Target selection comes from the options annotation rather than from the argument list: those are
        // the values that decide which file ends up under target/, and reading them here keeps publish in
        // step with whatever the WithCargo* methods emitted into the argument list.
        var options = resource.TryGetLastAnnotation<RustCargoOptionsAnnotation>(out var cargoOptions)
            ? cargoOptions
            : new RustCargoOptionsAnnotation();

        var metadata = await context.Services.GetRequiredService<ICargoMetadataReader>()
            // Publishing deliberately queries with an empty environment: the resource's environment applies
            // to the process the container runs, not to the host-side manifest query, and the container build
            // pins its own target directory regardless of what CARGO_TARGET_DIR says here.
            .ReadAsync(appDirectory, options.ManifestPath, resource.Name, ReadOnlyDictionary<string, string>.Empty, context.CancellationToken)
            .ConfigureAwait(false);

        // Only the app directory is copied into the image, so a workspace root above it never reaches the
        // build. Cargo cannot build a member without its workspace root manifest — inherited fields, path
        // dependencies and the lock file all live there — so this is reported rather than left to produce a
        // Dockerfile that cannot build.
        if (metadata.WorkspaceRoot is { Length: > 0 } workspaceRoot && !IsInsideAppDirectory(workspaceRoot, appDirectory))
        {
            throw new DistributedApplicationException(
                $"The Rust app '{resource.Name}' is a member of the cargo workspace rooted at '{workspaceRoot}', which is outside its " +
                $"app directory '{appDirectory}'. Publishing copies only the app directory into the container image, so point the app " +
                $"directory at the workspace root and select the member with WithCargoPackage(\"<name>\"), or add a Dockerfile next to " +
                $"Cargo.toml to take over the container build.");
        }

        var target = RustCargoTargetResolver.Resolve(
            metadata,
            options,
            context.Services.GetRequiredService<DistributedApplicationExecutionContext>(),
            resource.Name);

        // Cargo args must come from the same annotation pipeline that run mode uses, otherwise
        // WithCargoArgs/WithCargoFeatures configuration silently changes meaning at publish time. They are
        // read from `resource` rather than context.Resource because the latter is the ContainerResource that
        // PublishAsDockerFile substitutes in, which does not carry the Rust annotations.
        var cargoArgs = await ResolvePublishCargoArgsAsync(resource, context.CancellationToken).ConfigureAwait(false);

        // A manifest path configured for the host points somewhere that does not exist in the container, so
        // the copy of it that reaches `cargo build` has to be rewritten to sit under /app.
        if (options.ManifestPath is { } manifestPath)
        {
            RewriteManifestPath(cargoArgs, manifestPath, ToContainerPath(manifestPath, appDirectory, resource.Name));
        }

        var baseImageAnnotation = ResolveBaseImageAnnotation(resource, context);
        var images = RustPublishImageResolver.Resolve(
            baseImageAnnotation?.BuildImage,
            baseImageAnnotation?.RuntimeImage);

        var buildStage = context.Builder
            .From(images.BuildImage, "build")
            .WorkDir("/app");

        if (target.Target is { } triple)
        {
            // A cross target's standard library is not present in the base image, so it has to be installed
            // before cargo can build for it.
            buildStage.Run($"rustup target add {ShellQuote(triple)}");
        }

        buildStage
            .Copy(".", ".")
            // Cache the downloaded crate registry across builds. The target directory is deliberately NOT a
            // cache mount: cache mounts are not part of the resulting layer, so the COPY --from below would
            // not be able to see the binary.
            // CARGO_HOME is /usr/local/cargo in the official rust images; a cache mount on a path a custom
            // build image does not use is harmless. RUSTUP_HOME is deliberately not cached either: a cache
            // mount starts empty and shadows the directory it covers, so mounting one over /usr/local/rustup
            // hides the toolchains the image ships and rustup then fails with no default toolchain
            // configured. A crate pinning a toolchain the image does not carry therefore re-downloads it
            // whenever this COPY is invalidated.
            .RunWithMounts(
                $"{BuildCargoCommand(cargoArgs)}{CommandContinuation}{BuildCollectArtifactCommand(target)}",
                "type=cache,target=/usr/local/cargo/registry");

        // Add intermediate FROM stages for any container files sources (e.g. FROM frontend AS frontend_stage).
        context.Builder.AddContainerFilesStages(context.Resource, logger);

        var runtimeStage = context.Builder.From(images.RuntimeImage);

        // Nothing is installed into the runtime image. It provides exactly what it ships, whether it is the
        // default or one the caller chose, so a crate needing a CA bundle, a zoneinfo database or any other
        // package has to select an image that carries it or take over the build with its own Dockerfile.
        //
        // BusyBox and shadow-utils disagree on both the command names and their flags, and the runtime image
        // may ship either, so try one and fall back to the other rather than guessing from the image name.
        //
        // The ids are left to the tool to allocate. Pinning one looks appealing, since it would give a
        // mounted volume the same owner whichever branch ran, but there is no id that is free on every image:
        // alpine:3.22 already uses gid 999 for `ping`, and asking for it fails outright rather than falling
        // through to the next command. An image that needs a particular id can create the user itself and
        // supply its own Dockerfile.
        runtimeStage.Run(
            "(addgroup -S app || groupadd --system app) && " +
            "(adduser -S -G app app || useradd --system --gid app --no-create-home app)");

        runtimeStage
            .WorkDir("/app")
            // Add COPY --from=<source> instructions for each container files source.
            .AddContainerFiles(context.Resource, "/app", logger)
            // RelativePath is relative to cargo's target directory, which the build stage pins to a fixed
            // location so the crate's own configuration cannot move it.
            .CopyFrom("build", $"{ContainerArtifactDirectory}/{target.Name}", $"/app/{target.Name}")
            .User("app")
            .Entrypoint([$"/app/{target.Name}"]);
    }

    // Evaluates every cargo args callback exactly as run mode does — the publish-only defaults are added by
    // AddInitialCargoArgs, which sees the same execution context — then applies the arguments that exist
    // solely because the build runs in a container.
    private static async Task<List<string>> ResolvePublishCargoArgsAsync(
        RustAppResource resource,
        CancellationToken cancellationToken)
    {
        var args = new List<string>();

        foreach (var annotation in resource.Annotations.OfType<RustCargoArgsCallbackAnnotation>())
        {
            await annotation.Callback(new RustCargoArgsCallbackContext(args, cancellationToken)).ConfigureAwait(false);
        }

        var cargoArgs = args.Where(static arg => arg.Length > 0).ToList();

        // Appended last because cargo takes the last occurrence of a flag, so this overrides a --target-dir
        // that reached the list some other way as well as the crate's own configuration.
        cargoArgs.Add("--target-dir");
        cargoArgs.Add(ContainerTargetDirectory);

        return cargoArgs;
    }

    // The two-token form is what WithCargoManifestPath emits, so match on the pair rather than reformatting
    // the argument list. A --manifest-path passed as a raw string through WithCargoArgs is left alone, in
    // keeping with raw arguments being forwarded verbatim everywhere else.
    private static void RewriteManifestPath(List<string> cargoArgs, string hostPath, string containerPath)
    {
        for (var i = 0; i < cargoArgs.Count - 1; i++)
        {
            if (cargoArgs[i] == "--manifest-path" && cargoArgs[i + 1] == hostPath)
            {
                cargoArgs[i + 1] = containerPath;
            }
        }
    }

    // The app directory is the docker build context and is copied to /app, so a host path only has a
    // container equivalent when it sits inside that directory. A path outside it is not part of the build
    // context at all, so there is nothing to rewrite it to and no Dockerfile that could build the crate.
    private static string ToContainerPath(string hostPath, string appDirectory, string resourceName)
    {
        if (!IsInsideAppDirectory(hostPath, appDirectory))
        {
            throw new DistributedApplicationException(
                $"The Rust app '{resourceName}' builds from '{hostPath}', which is outside its app directory '{appDirectory}'. " +
                $"Publishing copies only the app directory into the container image, so point the app directory at a location that " +
                $"contains the whole crate, or add a Dockerfile next to Cargo.toml to take over the container build.");
        }

        var relative = Path.GetRelativePath(appDirectory, Path.GetFullPath(hostPath, appDirectory));

        return relative is "." ? "/app" : $"/app/{relative.Replace('\\', '/')}";
    }

    private static bool IsInsideAppDirectory(string hostPath, string appDirectory)
    {
        var relative = Path.GetRelativePath(appDirectory, Path.GetFullPath(hostPath, appDirectory));

        // GetRelativePath returns a rooted path when the two share no common root (different drives on
        // Windows), and a ..-prefixed path when the target is above the app directory.
        return !Path.IsPathRooted(relative)
            && relative != ".."
            && !relative.StartsWith("../", StringComparison.Ordinal)
            && !relative.StartsWith(@"..\", StringComparison.Ordinal);
    }

    private static string BuildCargoCommand(List<string> cargoArgs)
        => string.Join(" ", new[] { "cargo", "build" }.Concat(cargoArgs.Select(ShellQuote)));

    // Moves the freshly built binary to a fixed path so the runtime stage's COPY --from does not have to
    // know whether cargo inserted a target-triple directory. `--target` is only one of the ways a triple is
    // selected — `[build] target` in a .cargo/config.toml arrives with the build context, and
    // CARGO_BUILD_TARGET can come from the resource environment — so both layouts are searched rather than
    // one being predicted:
    //   /build/target/release/api            (host build)
    //   /build/target/x86_64-.../release/api (some target selected, by whatever means)
    // The explicit emptiness test reports the miss directly; without it the failure is a bare
    // `cp: cannot stat ''`, which says nothing about what was looked for.
    private static string BuildCollectArtifactCommand(RustCargoTarget target)
    {
        // Quoting only the suffix keeps the wildcard live: `/build/target/*/'my bin'` still globs, whereas
        // quoting the whole path would make the `*` literal.
        var suffix = ShellQuote(target.RelativePathWithoutTarget);
        var candidates = $"{ContainerTargetDirectory}/{suffix} {ContainerTargetDirectory}/*/{suffix}";
        var destination = $"{ContainerArtifactDirectory}/{ShellQuote(target.Name)}";

        return string.Join(
            CommandContinuation,
            [
                $"bin=\"$(ls -1d {candidates} 2>/dev/null | head -n1)\"",
                $"[ -n \"$bin\" ] || {{ echo \"cargo build produced no binary under {ContainerTargetDirectory}\" >&2; exit 1; }}",
                $"mkdir -p {ContainerArtifactDirectory}",
                $"cp \"$bin\" {destination}"
            ]);
    }

    // An explicit LF is used rather than Environment.NewLine or a raw string literal because a CR after the
    // backslash stops the shell treating the line as a continuation, and the Dockerfile is written verbatim.
    private const string CommandContinuation = " && \\\n    ";

    // Dockerfile RUN uses the shell form (/bin/sh -c), so user-supplied values such as bin target and feature
    // names must be quoted to avoid changing the command's meaning. Already-safe tokens (notably cargo's own
    // flags) are left bare so the generated Dockerfile stays readable.
    private static string ShellQuote(string value)
    {
        if (value.Length > 0 && value.All(static c => char.IsAsciiLetterOrDigit(c) || c is '-' or '_' or '.' or '/' or '=' or ',' or '+' or ':'))
        {
            return value;
        }

        // Single quotes suppress all shell expansion. An embedded single quote is emitted by closing the
        // quoted run, escaping the quote, then reopening: don't => 'don'\''t'.
        return $"'{value.Replace("'", "'\\''")}'";
    }

    // WithDockerfileBaseImage may be applied either to the Rust resource builder or, inside the
    // PublishAsDockerFile callback, to the substituted container resource. Check both so the override works
    // wherever the user attaches it.
    private static DockerfileBaseImageAnnotation? ResolveBaseImageAnnotation(RustAppResource resource, DockerfileBuilderCallbackContext context)
        => context.Resource.Annotations.OfType<DockerfileBaseImageAnnotation>().LastOrDefault()
            ?? resource.Annotations.OfType<DockerfileBaseImageAnnotation>().LastOrDefault();
}

